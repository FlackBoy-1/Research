# 1. Подключаем библиотеку pandas
# 'as pd' означает, что мы будем обращаться к ней по короткому имени 'pd'
import pandas as pd

# 2. Читаем файл
# Мы создаем переменную df (DataFrame) и кладем в нее таблицу из файла
df = pd.read_csv(
    'corpus.csv',           # Имя файла (он должен лежать в той же папке)
    sep=';',                # Разделитель колонок - точка с запятой
    encoding='utf-8-sig'    # Кодировка, чтобы не было ошибки с русскими буквами
)

# 3. Выводим первые 5 строк на экран
print("--- Первые 5 строк таблицы ---")
print(df.head())

# 4. Выводим структуру таблицы
print("\n--- Информация o таблице ---")
print(df.info())